"""
Base Strategy Class
Abstract base for all betting strategies

Phase 3.1: Added recommended_delay_seconds for anti-detection
Phase 3.2: Added stake_min/max for stake noise
Phase 2.1: Added ML confidence model integration
"""

import os
import random
import pandas as pd
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from typing import Optional, Dict, TYPE_CHECKING
from datetime import datetime
from loguru import logger
from cortex.match_state import MatchState

if TYPE_CHECKING:
    from backend.ml.confidence_model import ConfidenceModel
    from backend.utils.kelly_criterion import DynamicKellyManager


@dataclass
class Signal:
    """Betting signal generated by a strategy"""
    
    signal_id: str
    strategy: str
    action: str  # BACK or LAY
    team: str
    odds: float
    confidence: float  # 0.0 to 1.0
    stake_recommended: int
    edge_window_seconds: int
    reasoning: str
    match_context: Dict
    created_at: datetime
    
    # Phase 3.1: Recommended delay before placing bet (anti-detection)
    recommended_delay_seconds: int = 0
    
    # Phase 3.2: Stake range with noise
    stake_min: int = 0
    stake_max: int = 0
    
    def to_dict(self) -> Dict:
        """Convert to dictionary"""
        return {
            'signal_id': self.signal_id,
            'strategy': self.strategy,
            'action': self.action,
            'team': self.team,
            'odds': self.odds,
            'confidence': self.confidence,
            'stake_recommended': self.stake_recommended,
            'stake_min': self.stake_min,
            'stake_max': self.stake_max,
            'edge_window_seconds': self.edge_window_seconds,
            'recommended_delay_seconds': self.recommended_delay_seconds,
            'reasoning': self.reasoning,
            'match_context': self.match_context,
            'created_at': self.created_at.isoformat()
        }


class BaseStrategy(ABC):
    """Abstract base class for betting strategies"""
    
    def __init__(self, name: str, ml_model: 'ConfidenceModel' = None):
        self.name = name
        self.signals_generated = 0
        self.signals_suppressed = 0
        
        # Phase 2.1: ML confidence model integration
        self.ml_model = ml_model
        self.ml_weight = float(os.getenv('ML_CONFIDENCE_WEIGHT', '0.70'))  # 70% ML, 30% rules
        self.ml_predictions_used = 0
        self.ml_fallbacks = 0
        
        # Phase 3.2: Dynamic Kelly Manager
        self.kelly_manager: 'DynamicKellyManager' = None
        self.signals_blocked_by_risk = 0
        
        # Phase 3.1: Bet delay configuration
        self.delay_min = int(os.getenv('BET_DELAY_MIN_SECONDS', '5'))
        self.delay_max = int(os.getenv('BET_DELAY_MAX_SECONDS', '15'))
        
        # Phase 3.2: Stake noise configuration
        self.stake_noise_pct = float(os.getenv('STAKE_NOISE_PCT', '0.20'))
    
    def set_ml_model(self, ml_model: 'ConfidenceModel'):
        """
        Phase 2.1: Set ML model for confidence prediction
        
        Args:
            ml_model: Trained ConfidenceModel instance
        """
        self.ml_model = ml_model
        logger.info(f"🧠 ML model attached to {self.name} strategy")
    
    def set_kelly_manager(self, kelly_manager: 'DynamicKellyManager'):
        """
        Phase 3.2: Set Kelly manager for dynamic risk management
        
        Args:
            kelly_manager: DynamicKellyManager instance
        """
        self.kelly_manager = kelly_manager
        logger.info(f"💰 Kelly manager attached to {self.name} strategy")
    
    def blend_confidence(
        self, 
        rule_confidence: float, 
        odds: float,
        match_state: MatchState
    ) -> float:
        """
        Phase 2.1: Blend rule-based confidence with ML prediction
        
        Formula: final = ml_weight * ml_conf + (1 - ml_weight) * rule_conf
        
        Args:
            rule_confidence: Confidence from rule-based logic (0.0 to 1.0)
            odds: Current odds for the bet
            match_state: Current match state
            
        Returns:
            Blended confidence score
        """
        if self.ml_model is None:
            return rule_confidence
        
        try:
            # Prepare features for ML model
            features = pd.DataFrame([{
                'odds': odds,
                'strategy': self.name,
                'market': 'match_winner',
                'hour_of_day': datetime.utcnow().hour
            }])
            
            # Get ML prediction
            ml_confidence = self.ml_model.predict_confidence(features)[0]
            
            # Blend confidences
            blended = (self.ml_weight * ml_confidence) + ((1 - self.ml_weight) * rule_confidence)
            
            self.ml_predictions_used += 1
            
            logger.debug(
                f"🧠 ML Confidence Blend ({self.name}): "
                f"rules={rule_confidence:.2%}, ml={ml_confidence:.2%}, "
                f"blended={blended:.2%} (weight={self.ml_weight:.0%})"
            )
            
            return blended
            
        except Exception as e:
            logger.warning(f"ML confidence prediction failed, using rule-based: {e}")
            self.ml_fallbacks += 1
            return rule_confidence
    
    @abstractmethod
    def evaluate(self, state: MatchState, event: Dict) -> Optional[Signal]:
        """
        Evaluate match state and generate signal if conditions met
        
        Args:
            state: Current match state
            event: Latest market event
            
        Returns:
            Signal if conditions met, None otherwise
        """
        pass
    
    def _generate_signal_id(self, state: MatchState) -> str:
        """Generate unique signal ID"""
        timestamp = datetime.utcnow().strftime('%Y%m%d%H%M%S%f')
        return f"{self.name}_{state.match_id}_{timestamp}"
    
    def _calculate_kelly_stake(
        self, 
        confidence: float, 
        odds: float, 
        bankroll: int = 100000,
        kelly_fraction: float = 0.25
    ) -> int:
        """
        Calculate Kelly Criterion stake size
        
        Args:
            confidence: Win probability (0.0 to 1.0)
            odds: Decimal odds
            bankroll: Current bankroll
            kelly_fraction: Fraction of Kelly to use (0.25 = quarter Kelly)
            
        Returns:
            Recommended stake amount
        """
        # Kelly formula: f = (bp - q) / b
        # where: b = odds - 1, p = win probability, q = 1 - p
        
        b = odds - 1
        p = confidence
        q = 1 - p
        
        kelly = (b * p - q) / b
        
        # Apply fractional Kelly
        kelly = kelly * kelly_fraction
        
        # Ensure positive and within limits
        kelly = max(0, min(kelly, 0.05))  # Max 5% of bankroll
        
        stake = int(bankroll * kelly)
        
        # Minimum stake
        return max(stake, 1000)
    
    def _generate_random_delay(self) -> int:
        """
        Phase 3.1: Generate random delay before bet placement
        
        Helps avoid detection by varying bet timing.
        """
        return random.randint(self.delay_min, self.delay_max)
    
    def _calculate_stake_range(self, base_stake: int) -> tuple:
        """
        Phase 3.2: Calculate stake range with noise
        
        Returns (min_stake, max_stake) tuple.
        Actual stake should be chosen randomly from this range.
        """
        noise_amount = int(base_stake * self.stake_noise_pct)
        min_stake = max(1000, base_stake - noise_amount)  # Minimum 1000
        max_stake = base_stake + noise_amount
        return min_stake, max_stake
    
    def create_signal(
        self,
        match_state: MatchState,
        action: str,
        odds: float,
        confidence: float,
        edge: float,
        reasoning: str,
        use_ml_blend: bool = True
    ) -> Signal:
        """
        Create a signal with standard fields
        
        Args:
            match_state: Current match state
            action: BACK or LAY
            odds: Entry odds
            confidence: Win probability (0.0 to 1.0) - rule-based
            edge: Expected edge
            reasoning: Human-readable reasoning
            use_ml_blend: Whether to blend with ML confidence (default True)
            
        Returns:
            Signal object with anti-detection features
        """
        self.signals_generated += 1
        
        # Phase 2.1: Blend confidence with ML if available
        if use_ml_blend and self.ml_model is not None:
            final_confidence = self.blend_confidence(confidence, odds, match_state)
        else:
            final_confidence = confidence
        
        # Calculate base stake using blended confidence
        base_stake = self._calculate_kelly_stake(final_confidence, odds)
        
        # Phase 3.2: Apply dynamic Kelly brakes
        if self.kelly_manager:
            risk_result = self.kelly_manager.calculate_adjusted_stake(
                base_stake, 
                match_id=match_state.match_id
            )
            
            if risk_result['status'] == 'HALTED':
                logger.warning(f"🛑 Signal blocked by risk manager: {risk_result['reason']}")
                self.signals_blocked_by_risk += 1
                return None
            
            base_stake = risk_result['adjusted_stake']
            
            if risk_result['status'] == 'REDUCED':
                logger.warning(f"⚠️ Stake reduced by risk manager: {risk_result['reason']}")
        
        # Phase 3.1: Generate random delay
        delay = self._generate_random_delay()
        
        # Phase 3.2: Calculate stake range with noise
        stake_min, stake_max = self._calculate_stake_range(base_stake)
        
        return Signal(
            signal_id=self._generate_signal_id(match_state),
            strategy=self.name,
            action=action,
            team=match_state.batting_team,
            odds=odds,
            confidence=final_confidence,
            stake_recommended=base_stake,
            stake_min=stake_min,
            stake_max=stake_max,
            edge_window_seconds=45,
            recommended_delay_seconds=delay,
            reasoning=reasoning,
            match_context=match_state.to_dict(),
            created_at=datetime.utcnow()
        )
    
    def get_stats(self) -> Dict:
        """Get strategy statistics"""
        return {
            'name': self.name,
            'signals_generated': self.signals_generated,
            'signals_suppressed': self.signals_suppressed,
            # Phase 2.1: ML integration stats
            'ml_enabled': self.ml_model is not None,
            'ml_predictions_used': self.ml_predictions_used,
            'ml_fallbacks': self.ml_fallbacks,
            'ml_weight': self.ml_weight,
            # Phase 3.2: Risk management stats
            'kelly_manager_enabled': self.kelly_manager is not None,
            'signals_blocked_by_risk': self.signals_blocked_by_risk
        }

